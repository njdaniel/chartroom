// Command schema-ts writes the client's TypeScript protocol types,
// web/src/protocol.gen.ts, from the Go types in internal/protocol (ADR-001).
// Run it with `make gen` from the repo root. A test fails if the checked-in
// file is stale.
//
// Types come from reflection over protocol's message, intent, and event
// tables. Constants come from parsing the Go source, since reflection cannot
// see them.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"maps"
	"os"
	"path/filepath"
	"reflect"
	"slices"
	"strings"
	"time"

	"github.com/njdaniel/chartroom/internal/eventlog"
	"github.com/njdaniel/chartroom/internal/protocol"
)

// OutFile is where the generated file goes, relative to the repo root.
const OutFile = "web/src/protocol.gen.ts"

// constFiles hold the exported constants the client needs, relative to the
// repo root.
var constFiles = []string{
	"internal/protocol/intents.go",
	"internal/protocol/messages.go",
	"internal/table/events.go",
}

func main() {
	root := flag.String("root", ".", "repo root")
	flag.Parse()
	out, err := generate(*root)
	if err != nil {
		fmt.Fprintln(os.Stderr, "schema-ts:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(filepath.Join(*root, OutFile), out, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "schema-ts:", err)
		os.Exit(1)
	}
}

// renames give a TypeScript name where the Go name would clash or mislead.
var renames = map[reflect.Type]string{
	reflect.TypeFor[eventlog.Event](): "LogEvent", // protocol.Event is the frame that carries it
}

// marshalers are the types with their own JSON encoding that the generator
// knows how to describe. Any other json.Marshaler is an error, since its
// fields would not tell the truth about its JSON.
var marshalers = map[reflect.Type]string{
	reflect.TypeFor[time.Time]():       "string", // RFC 3339
	reflect.TypeFor[json.RawMessage](): "unknown",
	// SeatID encodes "" as null. Fields that can be "" say so with a ts tag.
	reflect.TypeFor[eventlog.SeatID](): "",
}

var jsonMarshaler = reflect.TypeFor[json.Marshaler]()

type generator struct {
	decls map[string]string // TypeScript name → declaration
	names map[reflect.Type]string
	// literal gives the "type" field of each message struct its value.
	literal map[reflect.Type]string
}

func generate(root string) ([]byte, error) {
	g := &generator{decls: map[string]string{}, names: map[reflect.Type]string{}, literal: map[reflect.Type]string{}}

	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/schema-ts from internal/protocol. DO NOT EDIT.\n")
	b.WriteString("// Regenerate with `make gen`.\n\n")

	consts, err := constants(root)
	if err != nil {
		return nil, err
	}
	b.WriteString(consts)

	clientMsgs, err := g.messages(protocol.ClientMessages)
	if err != nil {
		return nil, err
	}
	serverMsgs, err := g.messages(protocol.ServerMessages)
	if err != nil {
		return nil, err
	}
	intents, err := g.dataMap("IntentData", "Data for each intent kind.", protocol.IntentData)
	if err != nil {
		return nil, err
	}
	events, err := g.dataMap("EventData", "Data for each event type a client receives.", protocol.EventData)
	if err != nil {
		return nil, err
	}

	// KnownEvent below is built from LogEvent, which fields refer to only
	// through ts tags.
	if _, err := g.ts(reflect.TypeFor[eventlog.Event]()); err != nil {
		return nil, err
	}

	for _, name := range slices.Sorted(maps.Keys(g.decls)) {
		b.WriteString(g.decls[name])
		b.WriteString("\n")
	}

	b.WriteString(intents + "\n")
	b.WriteString(events + "\n")
	b.WriteString(`/** An intent with its data typed by kind. */
export type Intent = {
  [K in keyof IntentData]: Omit<IntentMessage, "kind" | "data"> & { kind: K; data: IntentData[K] };
}[keyof IntentData];

/** A log event with its data typed by event type. */
export type KnownEvent = {
  [K in keyof EventData]: Omit<LogEvent, "type" | "data"> & { type: K; data: EventData[K] };
}[keyof EventData];

`)
	fmt.Fprintf(&b, "/** Every frame a client sends. Intents use Intent, so their data is typed. */\nexport type ClientMessage = %s;\n\n",
		strings.Join(replace(clientMsgs, "IntentMessage", "Intent"), " | "))
	fmt.Fprintf(&b, "/** Every frame the server sends. */\nexport type ServerMessage = %s;\n", strings.Join(serverMsgs, " | "))
	return b.Bytes(), nil
}

// messages declares each message struct with its "type" field fixed, and
// returns their names in "type" order.
func (g *generator) messages(m map[string]any) ([]string, error) {
	var names []string
	for _, typ := range slices.Sorted(maps.Keys(m)) {
		t := reflect.TypeOf(m[typ])
		if f, ok := t.FieldByName("Type"); !ok || f.Tag.Get("json") != "type" {
			return nil, fmt.Errorf("message %s has no `json:\"type\"` Type field", t)
		}
		g.literal[t] = typ
		g.names[t] = t.Name() + "Message"
		name, err := g.ts(t)
		if err != nil {
			return nil, err
		}
		names = append(names, name)
	}
	return names, nil
}

// dataMap declares an interface from string keys to data types.
func (g *generator) dataMap(name, doc string, m map[string]any) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "/** %s */\nexport interface %s {\n", doc, name)
	for _, k := range slices.Sorted(maps.Keys(m)) {
		ts, err := g.ts(reflect.TypeOf(m[k]))
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "  %q: %s;\n", k, ts)
	}
	b.WriteString("}\n")
	return b.String(), nil
}

// ts returns the TypeScript for t, declaring named types as it goes.
func (g *generator) ts(t reflect.Type) (string, error) {
	if ts, ok := marshalers[t]; ok && ts != "" {
		return ts, nil
	}
	if t.Implements(jsonMarshaler) || reflect.PointerTo(t).Implements(jsonMarshaler) {
		if _, ok := marshalers[t]; !ok {
			return "", fmt.Errorf("%s has its own JSON encoding; add it to marshalers in cmd/schema-ts", t)
		}
	}

	switch t.Kind() {
	case reflect.String, reflect.Bool, reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Float32, reflect.Float64:
		base := map[reflect.Kind]string{reflect.String: "string", reflect.Bool: "boolean"}[t.Kind()]
		if base == "" {
			base = "number"
		}
		if t.PkgPath() == "" {
			return base, nil
		}
		return g.declare(t, func(name string) (string, error) {
			return fmt.Sprintf("export type %s = %s;\n", name, base), nil
		})
	case reflect.Pointer:
		elem, err := g.ts(t.Elem())
		return elem + " | null", err
	case reflect.Slice, reflect.Array:
		elem, err := g.ts(t.Elem())
		if strings.Contains(elem, " ") {
			elem = "(" + elem + ")"
		}
		return elem + "[]", err
	case reflect.Map:
		k, err := g.ts(t.Key())
		if err != nil {
			return "", err
		}
		v, err := g.ts(t.Elem())
		return fmt.Sprintf("Record<%s, %s>", k, v), err
	case reflect.Struct:
		return g.declare(t, func(name string) (string, error) { return g.iface(name, t) })
	default:
		return "", fmt.Errorf("no TypeScript for %s (kind %s)", t, t.Kind())
	}
}

// declare names t and adds its declaration once.
func (g *generator) declare(t reflect.Type, decl func(name string) (string, error)) (string, error) {
	name, ok := g.names[t]
	if !ok {
		name = renames[t]
		if name == "" {
			name = t.Name()
		}
		g.names[t] = name
	}
	if _, done := g.decls[name]; done {
		return name, nil
	}
	for other, n := range g.names {
		if n == name && other != t {
			return "", fmt.Errorf("%s and %s would both be %s in TypeScript; add a rename", t, other, name)
		}
	}
	g.decls[name] = "" // placeholder, so recursive types terminate
	d, err := decl(name)
	if err != nil {
		return "", err
	}
	g.decls[name] = d
	return name, nil
}

// iface declares a struct as an interface, the way encoding/json writes it.
func (g *generator) iface(name string, t reflect.Type) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "export interface %s {\n", name)
	if err := g.fields(&b, t); err != nil {
		return "", err
	}
	b.WriteString("}\n")
	return b.String(), nil
}

func (g *generator) fields(b *strings.Builder, t reflect.Type) error {
	for i := range t.NumField() {
		f := t.Field(i)
		tag := f.Tag.Get("json")
		if tag == "-" || (!f.IsExported() && !f.Anonymous) {
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		if f.Anonymous && name == "" && f.Type.Kind() == reflect.Struct {
			// encoding/json puts an embedded struct's fields in the outer object.
			if err := g.fields(b, f.Type); err != nil {
				return err
			}
			continue
		}
		if name == "" {
			name = f.Name
		}
		typ := f.Tag.Get("ts")
		if lit, ok := g.literal[t]; ok && f.Name == "Type" {
			typ = fmt.Sprintf("%q", lit)
		}
		if typ == "" {
			var err error
			if typ, err = g.ts(f.Type); err != nil {
				return fmt.Errorf("%s.%s: %w", t, f.Name, err)
			}
		}
		optional := ""
		if strings.Contains(","+opts+",", ",omitempty,") {
			optional = "?"
		}
		fmt.Fprintf(b, "  %s%s: %s;\n", name, optional, typ)
	}
	return nil
}

// constants returns every exported string or number constant in constFiles,
// with its comment.
func constants(root string) (string, error) {
	var b strings.Builder
	seen := map[string]string{}
	fset := token.NewFileSet()
	for _, path := range constFiles {
		f, err := parser.ParseFile(fset, filepath.Join(root, path), nil, parser.ParseComments)
		if err != nil {
			return "", err
		}
		fmt.Fprintf(&b, "// From %s.\n", path)
		for _, d := range f.Decls {
			gd, ok := d.(*ast.GenDecl)
			if !ok || gd.Tok != token.CONST {
				continue
			}
			if gd.Doc != nil {
				b.WriteString(comment(gd.Doc.Text()))
			}
			for _, spec := range gd.Specs {
				vs := spec.(*ast.ValueSpec)
				for i, n := range vs.Names {
					if !n.IsExported() || i >= len(vs.Values) {
						continue
					}
					lit, ok := vs.Values[i].(*ast.BasicLit)
					if !ok || (lit.Kind != token.STRING && lit.Kind != token.INT) {
						return "", fmt.Errorf("%s: constant %s is not a plain string or integer", path, n.Name)
					}
					if prev, dup := seen[n.Name]; dup {
						return "", fmt.Errorf("constant %s is in both %s and %s", n.Name, prev, path)
					}
					seen[n.Name] = path
					line := ""
					if vs.Comment != nil {
						line = " // " + strings.TrimSpace(vs.Comment.Text())
					}
					fmt.Fprintf(&b, "export const %s = %s;%s\n", n.Name, lit.Value, line)
				}
			}
			b.WriteString("\n")
		}
	}
	return b.String(), nil
}

func comment(text string) string {
	var b strings.Builder
	for _, line := range strings.Split(strings.TrimSpace(text), "\n") {
		b.WriteString(strings.TrimRight("// "+line, " ") + "\n")
	}
	return b.String()
}

func replace(s []string, old, new string) []string {
	out := slices.Clone(s)
	for i := range out {
		if out[i] == old {
			out[i] = new
		}
	}
	return out
}
